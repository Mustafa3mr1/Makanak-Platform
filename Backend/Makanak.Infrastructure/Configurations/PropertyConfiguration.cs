using Makanak.Domain.Entities;
using Makanak.Infrastructure.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Makanak.Infrastructure.Configurations;

public class PropertyConfiguration : IEntityTypeConfiguration<Property>
{
    public void Configure(EntityTypeBuilder<Property> builder)
    {
        builder.ToTable("Properties", t => t.HasCheckConstraint("CK_Properties_Price", "[Price] > 0"));
        builder.HasKey(p => p.Id);

        builder.Property(p => p.Title).IsRequired().HasMaxLength(200);
        builder.Property(p => p.Description).IsRequired().HasMaxLength(4000);
        builder.Property(p => p.Price).HasPrecision(18, 2);
        builder.Property(p => p.City).IsRequired().HasMaxLength(100);
        builder.Property(p => p.Address).IsRequired().HasMaxLength(300);

        builder.Property(p => p.Status).HasConversion<string>().HasMaxLength(30).IsRequired();
        builder.Property(p => p.PropertyType).HasConversion<string>().HasMaxLength(30).IsRequired();
        builder.Property(p => p.ListingType).HasConversion<string>().HasMaxLength(30).IsRequired();

        // SQL Server rowversion: generated by the database, never set by the application.
        builder.Property(p => p.RowVersion).IsRowVersion();

        builder.Property(p => p.CreatedAtUtc).IsRequired();
        builder.Property(p => p.UpdatedAtUtc).IsRequired();

        // Owner: Restrict so removing a user can never cascade into properties/offers/history.
        builder.HasOne<ApplicationUser>()
            .WithMany()
            .HasForeignKey(p => p.OwnerId)
            .OnDelete(DeleteBehavior.Restrict);

        // Images are owned content of the property; properties are soft-deleted, so cascade only matters for hard deletes.
        builder.HasMany(p => p.Images)
            .WithOne(i => i.Property)
            .HasForeignKey(i => i.PropertyId)
            .OnDelete(DeleteBehavior.Cascade);

        // Offers (and thus negotiation history) must survive: Restrict.
        builder.HasMany(p => p.Offers)
            .WithOne(o => o.Property)
            .HasForeignKey(o => o.PropertyId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.HasIndex(p => p.OwnerId);
        builder.HasIndex(p => new { p.Status, p.ListingType, p.PropertyType, p.City });
        builder.HasIndex(p => p.Price);
        builder.HasIndex(p => p.CreatedAtUtc);
    }
}
